import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {meshopt} from '@gltf-transform/functions';
import {MeshoptDecoder,MeshoptEncoder} from 'meshoptimizer';
import {readFileSync,copyFileSync,writeFileSync} from 'node:fs';
import {restoreStaticModelRoots} from './static-model-roots.js';
await MeshoptDecoder.ready;await MeshoptEncoder.ready;
const folder='content/maps/ironworks-v2/',source=folder+'model.glb';
copyFileSync(source,'D:/DroneLiftoffArtBuild/ironworks-site/model-flat.glb');
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.decoder':MeshoptDecoder,'meshopt.encoder':MeshoptEncoder});
const doc=await io.read(source),definition=JSON.parse(readFileSync(folder+'map.json'));
const names=[definition.modelNode,...definition.objects.flatMap(o=>o.modelLods.map(l=>l.modelNode))];
restoreStaticModelRoots(doc,names);
await doc.transform(meshopt({encoder:MeshoptEncoder,level:'medium'}));
await io.write('D:/DroneLiftoffArtBuild/ironworks-site/model.glb',doc);
copyFileSync('D:/DroneLiftoffArtBuild/ironworks-site/model.glb',source);
const report={selectors:names.length,missing:names.filter(n=>doc.getRoot().listNodes().filter(o=>o.getName()===n).length!==1),status:'Named chunk hierarchy restored; in-game check pending'};
if(report.missing.length)throw new Error(JSON.stringify(report));
writeFileSync(folder+'hierarchy-validation.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
